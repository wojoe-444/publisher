import { createHash } from "node:crypto";
import { components } from "../api";
import {
   BadRequestError,
   CompileRefusedError,
   FrozenConfigError,
   InvalidModelPathError,
   ModelNotFoundError,
   NotQueryableError,
   WriteConflictError,
   WriteVerifyError,
} from "../errors";
import { logger } from "../logger";
import { assertSafeRelativeModelPath } from "../path_safety";
import { EnvironmentStore } from "../service/environment_store";
import { formatProblem } from "../service/query_text";
import { carriesArtifactTag, reportWritePathProblem } from "../service/report";

type ApiModel = components["schemas"]["Model"];
type ApiCompiledModel = components["schemas"]["CompiledModel"];
type ApiModelSourceWrite = components["schemas"]["ModelSourceWriteRequest"];
type ApiModelSourceWriteResult =
   components["schemas"]["ModelSourceWriteResult"];

/**
 * The first line of a model written by the model builder. Only a file that
 * starts with it can be replaced through the model-file write path, so the
 * path cannot be used to overwrite a model a person wrote by hand.
 */
export const MODEL_BUILDER_MARKER = "// Generated by Malloy UI";

const hashOf = (text: string): string =>
   createHash("sha256").update(text, "utf8").digest("hex");

/**
 * `includeHiddenFilesAndSources`: also show the files a package's surface hides. It
 * changes what the model routes show, never what a query can reach, and
 * Publisher does not decide who may ask: the gateway in front of it does.
 */
export interface ModelReadOptions {
   includeHiddenFilesAndSources?: boolean;
}

export class ModelController {
   private environmentStore: EnvironmentStore;

   constructor(environmentStore: EnvironmentStore) {
      this.environmentStore = environmentStore;
   }

   public async listModels(
      environmentName: string,
      packageName: string,
      options: ModelReadOptions = {},
   ): Promise<ApiModel[]> {
      const environment = await this.environmentStore.getEnvironment(
         environmentName,
         false,
      );
      const p = await environment.getPackage(packageName, false);
      return p.listModels(options);
   }

   public async getModel(
      environmentName: string,
      packageName: string,
      modelPath: string,
      options: ModelReadOptions = {},
   ): Promise<ApiCompiledModel> {
      const includeHiddenFilesAndSources =
         options.includeHiddenFilesAndSources === true;
      try {
         const environment = await this.environmentStore.getEnvironment(
            environmentName,
            false,
         );
         const p = await environment.getPackage(packageName, false);
         const model = p.getModel(modelPath);
         if (!model) {
            throw new ModelNotFoundError(`${modelPath} does not exist`);
         }
         if (model.getType() === "notebook") {
            throw new ModelNotFoundError(`${modelPath} is a notebook`);
         }
         // A file nobody can query is not shown either: same rule, same 404
         // text as the query route.
         if (!includeHiddenFilesAndSources) model.assertFileOnSurface();
         // The file text is read without the package lock (callers reachable
         // from `Model.getModel()` must not take it): a mid-swap read sees the
         // old file, the new one, or ENOENT, and ENOENT only withholds the text.
         const [compiled, sourceText] = await Promise.all([
            model.getModel(),
            // Withheld when the text names a source the file does not publish,
            // unless the caller asked to see the files off the surface.
            p
               .getModelFileText(modelPath)
               .then((text) =>
                  includeHiddenFilesAndSources || model.showsFileText(text)
                     ? text
                     : undefined,
               )
               .catch((error: unknown) => {
                  logger.warn("getModel: model source text unavailable", {
                     environmentName,
                     packageName,
                     modelPath,
                     error:
                        error instanceof Error ? error.message : String(error),
                  });
                  return undefined;
               }),
         ]);
         return sourceText === undefined
            ? compiled
            : { ...compiled, sourceText };
      } catch (error) {
         // Re-throw these as-is, so they keep their 404.
         if (
            error instanceof ModelNotFoundError ||
            error instanceof NotQueryableError
         ) {
            throw error;
         }
         throw new Error(
            `Failed to get model ${modelPath} from package ${packageName} in environment ${environmentName}: ${error}`,
         );
      }
   }
   /**
    * Write a model file produced by the model builder into the package and
    * serve it. Compiles the text as the file and refuses without writing if it
    * does not compile; then, under one hold of the package lock, checks the
    * precondition, writes atomically and reloads, putting the previous text
    * back if the reload does not take the file (the same transaction a report
    * save uses).
    *
    * - CREATE (no `expectedHash`): any `.malloy` path that does not exist yet,
    *   outside `public/`, never the root `index.malloy`. An existing file is a
    *   409, so leaving the hash out is never an unconditional overwrite.
    * - REPLACE (`expectedHash`): only a file the model builder wrote (it
    *   starts with {@link MODEL_BUILDER_MARKER}) whose text still hashes to
    *   `expectedHash`.
    *
    * Text carrying an artifact tag is a report and belongs to the report save.
    */
   public async putModelFile(
      environmentName: string,
      packageName: string,
      modelPath: string,
      body: ApiModelSourceWrite,
   ): Promise<ApiModelSourceWriteResult> {
      if (this.environmentStore.publisherConfigIsFrozen) {
         throw new FrozenConfigError(
            'Cannot write a model: publisher.config.json has "frozenConfig": true.',
         );
      }
      try {
         assertSafeRelativeModelPath(modelPath);
      } catch (error) {
         throw new InvalidModelPathError((error as Error).message);
      }
      const pathProblem = reportWritePathProblem(modelPath);
      if (pathProblem) throw new InvalidModelPathError(pathProblem);
      if (typeof body?.source !== "string") {
         throw new BadRequestError(
            "The request body needs a `source`: the whole file's Malloy text.",
         );
      }
      if (!body.source.startsWith(MODEL_BUILDER_MARKER)) {
         throw new BadRequestError(
            `A model written here must start with \`${MODEL_BUILDER_MARKER}\`.`,
         );
      }
      if (carriesArtifactTag(body.source)) {
         throw new BadRequestError(
            "Text with an `## artifact` tag is a report; save it through the report write.",
         );
      }
      const environment = await this.environmentStore.getEnvironment(
         environmentName,
         false,
      );
      // Loads the package, or 404s.
      await environment.getPackage(packageName, false);

      const { problems } = await environment.compileSource(
         packageName,
         modelPath,
         body.source,
         false,
         undefined,
         "file",
      );
      const errors = problems.filter((problem) => problem.severity === "error");
      if (errors.length > 0) {
         throw new CompileRefusedError(
            `The model does not compile, so it was not written: ` +
               errors.map(formatProblem).join("; "),
         );
      }

      const { previous } = await environment.writeModelFileTransactional(
         packageName,
         modelPath,
         body.source,
         (current) => {
            if (body.expectedHash === undefined) {
               if (current !== undefined)
                  throw new WriteConflictError(
                     `\`${modelPath}\` already exists in the package, so nothing ` +
                        `was written. Choose another path, or send the ` +
                        `\`expectedHash\` of the text you opened to replace it.`,
                  );
               return;
            }
            if (current === undefined)
               throw new WriteConflictError(
                  `\`${modelPath}\` no longer exists in the package, so the text you ` +
                     `opened cannot be updated.`,
               );
            if (!current.startsWith(MODEL_BUILDER_MARKER))
               throw new BadRequestError(
                  `\`${modelPath}\` was not written by the model builder, so it was ` +
                     `not overwritten.`,
               );
            if (hashOf(current) !== body.expectedHash)
               throw new WriteConflictError(
                  `\`${modelPath}\` changed in the package since you opened it. ` +
                     `Re-open it and reapply your change; nothing was written.`,
               );
         },
         async (reloaded) => {
            const written = reloaded.getModel(modelPath);
            if (!written)
               throw new WriteVerifyError(
                  `\`${modelPath}\` is not in the reloaded package`,
               );
            await written.getModel().catch((cause) => {
               throw new WriteVerifyError(
                  `\`${modelPath}\` did not compile once the package reloaded`,
                  { cause },
               );
            });
         },
      );
      return {
         resource: `/api/v0/environments/${environmentName}/packages/${packageName}/models/${modelPath}`,
         path: modelPath,
         contentHash: hashOf(body.source),
         created: previous === undefined,
      };
   }
}
