import { describe, expect, it, spyOn } from "bun:test";
import express from "express";
import request from "supertest";
import type { ModelController } from "../controller/model.controller";
import { WriteConflictError } from "../errors";
import { logger } from "../logger";
import { linesMentioning } from "../test_helpers/log_lines";
import { modelWriteRoute } from "./model_write";

describe("modelWriteRoute", () => {
   const app = (putModelFile: () => Promise<unknown>) => {
      const server = express();
      server.use(express.json());
      server.put(
         "/api/v0/environments/:environmentName/packages/:packageName/model-files/*",
         modelWriteRoute({ putModelFile } as unknown as ModelController),
      );
      return server;
   };
   const put = (server: express.Express, file: string) =>
      request(server)
         .put(`/api/v0/environments/env/packages/pkg/model-files/${file}`)
         .send({ source: "// Generated by Malloy UI\n" });

   it("answers 201 for a new file and 200 for a replaced one", async () => {
      const created = await put(
         app(async () => ({ created: true })),
         "models/new.malloy",
      );
      expect(created.status).toBe(201);
      const replaced = await put(
         app(async () => ({ created: false })),
         "models/old.malloy",
      );
      expect(replaced.status).toBe(200);
   });

   it("passes the nested path through, not just its first segment", async () => {
      let seen = "";
      const server = express();
      server.use(express.json());
      server.put(
         "/api/v0/environments/:environmentName/packages/:packageName/model-files/*",
         modelWriteRoute({
            putModelFile: async (_e: string, _p: string, path: string) => {
               seen = path;
               return { created: true };
            },
         } as unknown as ModelController),
      );
      await put(server, "models/deep/sales.malloy");
      expect(seen).toBe("models/deep/sales.malloy");
   });

   it("logs a refusal once, at warn, with its status", async () => {
      const warn = spyOn(logger, "warn");
      try {
         const res = await put(
            app(async () => {
               throw new WriteConflictError("stale-model-409-marker");
            }),
            "models/stale.malloy",
         );
         expect(res.status).toBe(409);
         expect(linesMentioning(warn, "stale-model-409-marker")).toHaveLength(
            1,
         );
      } finally {
         warn.mockRestore();
      }
   });

   it("refuses a pinned version", async () => {
      const res = await request(app(async () => ({ created: true })))
         .put(
            "/api/v0/environments/env/packages/pkg/model-files/a.malloy?versionId=1",
         )
         .send({ source: "x" });
      expect(res.status).toBeGreaterThanOrEqual(400);
   });
});
